import { test, expect } from '@playwright/test';
test('elte loads, synchronizes contact, pauses, dies and reuses its independent rig', async ({ page }) => {
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error'||(m.type()==='warning'&&/PropertyBinding|GLTF|AnimationMixer|elte/i.test(m.text())))errors.push(m.text());});
  await page.goto('/?qa');await page.locator('#start').click();
  const result=await page.evaluate(async()=>{
    const {updateEnemy}=await import('/src/ai/EnemyAI.js');
    const g=window.__RED_HORIZON__,r=g.run;g.pause();r.director.timer=999;r.enemies=[];g.entities.sync(r);
    const e=r.spawn('elite',0,0), other=r.spawn('elite',4,0);e.y=e.height;other.y=other.height;
    g.entities.sync(r);const mesh=g.entities.enemies.get(e.id),mesh2=g.entities.enemies.get(other.id);
    await Promise.all([mesh.userData.elteReady,mesh2.userData.elteReady]);g.entities.sync(r);
    const a=g.entities.elteAvatars.get(mesh),b=g.entities.elteAvatars.get(mesh2),names=[a.clip];
    const distinct=a.root.getObjectByName('mixamorigHips')!==b.root.getObjectByName('mixamorigHips');
    const forward=a.root.rotation.y;
    e.state='Chase';r.time+=.1;g.entities.sync(r);names.push(a.clip);
    r.player.x=0;r.player.z=1;r.player.y=e.y-e.height;e.attackTimer=0;
    let hits=0;r.hurtPlayer=()=>{hits++;};updateEnemy(e,0,r);const start=r.time;g.entities.sync(r);names.push(a.clip);
    r.time=start+11/30;updateEnemy(e,1/60,r);g.entities.sync(r);const before=hits;
    r.time=start+12/30;updateEnemy(e,1/60,r);g.entities.sync(r);const contact={hits,time:a.clipTime};
    for(let i=0;i<10;i++)g.entities.sync(r);const frozen=a.clipTime===contact.time;
    r.time=start+.8;updateEnemy(e,0,r);e.attackTimer=0;updateEnemy(e,0,r);const altStart=r.time;g.entities.sync(r);names.push(a.clip);
    r.time=altStart+15/30;updateEnemy(e,0,r);g.entities.sync(r);const altBefore=hits;
    r.time=altStart+16/30;updateEnemy(e,0,r);g.entities.sync(r);const alternate={hits,time:a.clipTime};
    e.stun=.2;updateEnemy(e,0,r);g.entities.sync(r);names.push(a.clip);
    e.dead=true;r.enemies=r.enemies.filter(x=>x!==e);g.entities.sync(r);names.push(a.clip);
    const retained=g.entities.corpses.has(mesh)&&mesh.visible;
    r.time+=2.2;g.entities.sync(r);const finalVisible=g.entities.corpses.has(mesh)&&mesh.visible;
    r.time+=.6;g.entities.sync(r);const hidden=!mesh.visible&&!g.entities.corpses.has(mesh);
    const replacement=r.spawn('elite',0,0);replacement.y=replacement.height;g.entities.sync(r);
    const reused=g.entities.enemies.get(replacement.id)===mesh&&a.clip==='idle'&&a.clipTime===0;
    document.querySelector('#interface').hidden=true;g.world.group.visible=false;g.missionView.group.visible=false;g.view.sky.visible=false;g.missionView.update=()=>{};
    g.view.scene.background.set('#17212a');g.view.scene.fog=null;g.entities.player.scale.setScalar(0);g.particles.dustMesh.visible=false;g.particles.reset();
    const fill=g.view.sun.clone();fill.intensity=3;fill.castShadow=false;fill.position.set(2,5,5);g.view.scene.add(fill);
    g.camera.update=()=>{g.view.camera.position.set(4,3,5);g.view.camera.lookAt(0,1.1,0);};
    return {label:e.name,altBefore,alternate,names,distinct,forward,before,contact,frozen,retained,finalVisible,hidden,reused};
  });
  expect(result.names).toEqual(['idle','move','attack_melee','attack_melee_alt','idle','death']);
  expect(result.label).toBe('ELTE · Sobrecarga');expect(result.altBefore).toBe(1);expect(result.alternate.hits).toBe(2);expect(result.alternate.time).toBeCloseTo(16/30,5);
  expect(result.before).toBe(0);expect(result.contact.hits).toBe(1);expect(result.contact.time).toBeCloseTo(.4,5);
  expect(result.forward).toBeCloseTo(0);
  for(const key of ['distinct','frozen','retained','finalVisible','hidden','reused'])expect(result[key],key).toBe(true);
  await page.screenshot({path:'Modelos_Animados/elte/in-game.png'});
  expect(errors).toEqual([]);
});
